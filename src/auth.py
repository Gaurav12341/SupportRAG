"""Stage 7 (login): passwords and JWT tokens for the demo users. SIMULATED org: three demo users, real mechanics.

- Passwords are stored as salted scrypt hashes (standard library) in the `credentials` table of the access database. The plain
  passwords are generated by `python -m scripts.setup_users`, printed once, and kept nowhere.
- A token is an HS256 JWT signed with `JWT_SECRET` from .env (never in config.yaml or git). It carries only the user id and an expiry;
  the role and licenses are read from the database on every request, so revoking a license or removing a user works at once.
- Five wrong passwords for one user lock that user out of logging in for a minute (in memory; a restart clears it).
"""
import base64
import hashlib
import hmac
import os
import time

import jwt
from dotenv import load_dotenv

load_dotenv()

ALG = "HS256"
SCRYPT = dict(n=2 ** 14, r=8, p=1, dklen=32)
MAX_FAILS, LOCK_SECONDS = 5, 60
_fails = {}   # user -> (count, time of last failure)


class AuthError(Exception):
    """Login or token problem. The message is safe to show to the caller (it never says which part was wrong)."""


b64 = lambda b: base64.b64encode(b).decode()


def hash_password(password, salt=None):
    salt = salt or os.urandom(16)
    return f"scrypt${b64(salt)}${b64(hashlib.scrypt(password.encode(), salt=salt, **SCRYPT))}"


def verify_password(password, stored):
    try:
        _, salt, digest = stored.split("$")
        got = hashlib.scrypt(password.encode(), salt=base64.b64decode(salt), **SCRYPT)
        return hmac.compare_digest(got, base64.b64decode(digest))
    except (ValueError, AttributeError):
        return False


def ensure_table(store):
    store.db.execute("CREATE TABLE IF NOT EXISTS credentials (user_id TEXT PRIMARY KEY REFERENCES users(user_id), password_hash TEXT NOT NULL)")
    store.db.commit()


def set_password(store, user_id, password):
    ensure_table(store)
    store.db.execute("INSERT OR REPLACE INTO credentials VALUES (?, ?)", (user_id, hash_password(password)))
    store.db.commit()


def secret():
    key = os.getenv("JWT_SECRET")
    if not key or len(key) < 32:
        raise RuntimeError("JWT_SECRET is missing or too short in .env; run `python -m scripts.setup_users`")
    return key


def make_token(user_id, cfg, now=None):
    now = int(now or time.time())
    return jwt.encode({"sub": user_id, "iat": now, "exp": now + 60 * cfg["auth"]["token_minutes"]}, secret(), algorithm=ALG)


def read_token(token, store):
    """The user id in a valid, unexpired token whose user still exists. Raises AuthError otherwise."""
    try:
        user_id = jwt.decode(token, secret(), algorithms=[ALG], options={"require": ["exp", "sub"]})["sub"]
    except jwt.PyJWTError:
        raise AuthError("Invalid or expired token. Please log in again.") from None
    if store.role_of(user_id) is None:
        raise AuthError("Invalid or expired token. Please log in again.")
    return user_id


def login(store, user_id, password, cfg, now=None):
    """Token for a correct user/password. Always the same error for a wrong user or password; a locked user waits a minute."""
    now = now or time.time()
    count, last = _fails.get(user_id, (0, 0))
    if count >= MAX_FAILS and now - last < LOCK_SECONDS:
        raise AuthError("Too many failed logins. Try again in a minute.")
    ensure_table(store)
    row = store.db.execute("SELECT password_hash FROM credentials WHERE user_id=?", (user_id,)).fetchone()
    ok = verify_password(password, row[0] if row else hash_password("dummy"))  # the same work whether or not the user exists
    if not (row and ok):
        _fails[user_id] = (count + 1 if now - last < LOCK_SECONDS else 1, now)
        raise AuthError("Wrong user or password.")
    _fails.pop(user_id, None)
    return make_token(user_id, cfg, now)
